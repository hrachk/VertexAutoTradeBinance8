namespace VertexAutoTradeBinance8.Configuration;

/// <summary>
/// Параметры методологии уровней. Значения по умолчанию подобраны для
/// внутридневных таймфреймов (1–15 минут) на ликвидных фьючерсах.
///
/// Каждое поле — торговое решение, а не «настройка». Комментарий объясняет,
/// что именно ломается при его изменении.
/// </summary>
public class LevelOptions
{
    /// <summary>
    /// Включён ли новый движок уровней. False — работает прежний
    /// AiStopLossOptimizer. Оставлено для отката без пересборки: сначала
    /// стоит посмотреть в журнале решений, что и почему новый движок отклоняет.
    /// </summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// Глубина поиска структуры в свечах. Меньше — стоп цепляется за локальный
    /// шум; больше — уползает к старым уровням, которые рынок уже не помнит.
    /// </summary>
    public int LookbackBars { get; set; } = 60;

    /// <summary>
    /// Сколько соседних баров с каждой стороны должны быть выше (ниже), чтобы
    /// бар считался пивотом. 2 = классический фрактал. Больше — уровней меньше,
    /// но они значимее.
    /// </summary>
    public int PivotWidth { get; set; } = 2;

    /// <summary>
    /// Отступ за уровень структуры в ATR. Уровни пробивают хвостами: стоп
    /// ровно на уровне снимается шумом при ещё живой идее.
    /// </summary>
    public decimal StructureBufferAtr { get; set; } = 0.35m;

    /// <summary>
    /// Минимальная дистанция стопа в ATR. Ближе — обычное дыхание рынка
    /// выбивает позицию независимо от правоты идеи.
    /// </summary>
    public decimal MinStopAtr { get; set; } = 0.9m;

    /// <summary>
    /// Потолок дистанции в ATR. Дальше сделка отклоняется, а НЕ ужимается
    /// по объёму: маленькая позиция с плохим R:R — это всё ещё плохая сделка.
    /// </summary>
    public decimal MaxStopAtr { get; set; } = 3.0m;

    /// <summary>Второй потолок, в процентах от цены — страховка на всплесках ATR.</summary>
    public decimal MaxStopPercent { get; set; } = 2.5m;

    /// <summary>Дистанция стопа, когда структуры в окне не нашлось.</summary>
    public decimal FallbackStopAtr { get; set; } = 1.5m;

    /// <summary>
    /// Лестница целей в единицах риска. 1R закрывает часть и снимает
    /// напряжение, 2R — основная цель, 3.5R — раннер.
    /// </summary>
    public List<decimal> TpRMultiples { get; set; } = new() { 1.0m, 2.0m, 3.5m };

    /// <summary>
    /// Отступ перед встречной стенкой в ATR. Ставить цель вплотную к уровню
    /// значит регулярно не доезжать до неё несколько тиков.
    /// </summary>
    public decimal BarrierPadAtr { get; set; } = 0.25m;

    /// <summary>
    /// Минимальный R:R по первой цели. Ниже — сделка не окупает риск,
    /// и вход отклоняется с причиной LowRR или NoRoomToTarget.
    /// </summary>
    public decimal MinRiskReward { get; set; } = 1.5m;
}
